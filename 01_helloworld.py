#This program simply displays the functionality of print function
#It has two parameters, "end" and "sep"

#In "end" parameter we define how the print statement will end
#new line is by default, we cane change it to same line by adding empty quotes, tab space, etc.
print("Hello World!",end="\t")
print("How you doin!")
print("It is gonna be Legen.. (wait for it)",end="\n\n")
print("-Daryy!!")

#"sep" parameter we define the seperation between elements
print("h","e","l","l","o")
print("h","e","l","l","o",sep="")
print("08","10","12",sep="-")
print("bob","evilcorp",sep="@")
